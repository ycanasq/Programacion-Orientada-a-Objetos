    private void btnCreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateActionPerformed
        try{
            String newName = String.valueOf(txtName.getText());
            long newNumber = Long.parseLong(txtNumber.getText());
            
            String nameNumberString;
            String name;
            long number;
         
            
            File file = new File("/Users/MacBook/Documents/POO/Trabajo5/friendsContact.txt");
            
            if (file.exists()==false) {
                file.createNewFile();
            }
            
            RandomAccessFile raf = new RandomAccessFile(file, "rw");
            boolean found = false;
            
            while (raf.getFilePointer() < raf.length()) {
                nameNumberString = raf.readLine();
                String[] lineSplit = nameNumberString.split("!");
                name = lineSplit[0];
                number = Long.parseLong(lineSplit[1]);
                
                if (name.equals(newName)|| number == newNumber) {
                    found = true;
                    break;
                }
            }
            
            if (found == false){
                nameNumberString = newName + "!" + String.valueOf(newNumber);
                raf.writeBytes(nameNumberString);
                raf.writeBytes(System.lineSeparator());
                JOptionPane.showMessageDialog(null, "Friend added.");
                txtName.setText("");
                txtNumber.setText("");
                raf.close();
            }
            
            else {
                raf.close();
                JOptionPane.showMessageDialog(null, "Friend name already exists.");
                txtName.setText("");
                txtNumber.setText("");
            } 
        }
        
        catch (IOException ioe) {
            JOptionPane.showMessageDialog(null, "An error has occurred creating or opening the file. ");
            txtName.setText("");
            txtNumber.setText("");
        }
        catch (NumberFormatException nef) {
            JOptionPane.showMessageDialog(null, "A number format error has occurred.");
            txtName.setText("");
            txtNumber.setText("");
        }
    }//GEN-LAST:event_btnCreateActionPerformed

