    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        try {
            String updateName = String.valueOf(txtName.getText());
            long newNumber = Long.parseLong(txtNumber.getText());
            
            String nameNumberString;
            String name;
            long number;
            int index;
            
            File file = new File("/Users/MacBook/Documents/POO/Trabajo5/friendsContact.txt");
            
            if (file.exists()==false) {
                file.createNewFile();
            }
            
            RandomAccessFile raf = new RandomAccessFile(file, "rw");
            boolean found = false;
            
            while (raf.getFilePointer() < raf.length()) {
                nameNumberString = raf.readLine();
                String[] lineSplit = nameNumberString.split("!");
                
                name = lineSplit[0];
                number = Long.parseLong(lineSplit[1]);
                
                if (name.equals(updateName)) {
                    found = true;
                    break;
                }
            }
            
            if (found == true) {
                File tmpFile = new File("/Users/MacBook/Documents/POO/Trabajo5/temp.txt");
                
                RandomAccessFile tmpraf = new RandomAccessFile(tmpFile, "rw");
                
                raf.seek(0);
                
                while (raf.getFilePointer() < raf.length()) {
                    nameNumberString = raf.readLine();
                    
                    index = nameNumberString.indexOf("!");
                    name = nameNumberString.substring(0, index);
                    
                    if (name.equals(updateName)) {
                        nameNumberString = name + "!" + String.valueOf(newNumber);
                        continue;
                    }
                    
                    tmpraf.writeBytes(nameNumberString);
                    tmpraf.writeBytes(System.lineSeparator());
                    break;
                }
                
                raf.seek(0);
                tmpraf.seek(0);
                
                while (tmpraf.getFilePointer() < tmpraf.length()) {
                    raf.writeBytes(tmpraf.readLine());
                    raf.writeBytes(System.lineSeparator());
                    break;
                }
                
                raf.setLength(tmpraf.length());
                
                tmpraf.close();
                raf.close();
                
                tmpFile.delete();
                
                JOptionPane.showMessageDialog(null, "The name was updated.");

            }
            
            else {
                raf.close();
                JOptionPane.showMessageDialog(null, "The name you want to update does not exist.");
            
            }    
        }
        
        catch (IOException ioe) {
            JOptionPane.showMessageDialog(null, "An error has occurred creating or opening the file. ");
        }
        catch (NumberFormatException nef) {
            JOptionPane.showMessageDialog(null, "A number format error has occurred.");
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

